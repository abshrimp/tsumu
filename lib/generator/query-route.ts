/**
 * Static URL query variants. One physical HTML file can display multiple
 * authored pages based on the browser's URLSearchParams, without a server.
 * The selected fragment must be ready (including its authored scripts) before
 * the generated data loader and event runtime are started.
 */
export const QUERY_VARIANT_RUNTIME = [
  "(function () {",
  '  const host = document.querySelector("[data-variant-root]");',
  '  const config = document.querySelector("script[data-page-variants]");',
  '  const entry = document.currentScript;',
  "  if (!host || !config || !entry) return;",
  "  let choices = [], runtimeSources = [];",
  '  try { choices = JSON.parse(config.textContent || "[]");',
  '    runtimeSources = JSON.parse(entry.getAttribute("data-runtime-sources") || "[]"); }',
  '  catch (error) { console.warn("Invalid query variants", error); return; }',
  "  const search = new URLSearchParams(location.search);",
  "  const matching = choices.filter(function (choice) {",
  "    return Object.entries(choice.query).every(function (pair) {",
  "      return search.get(pair[0]) === pair[1];",
  "    });",
  "  });",
  "  matching.sort(function (a, b) {",
  "    return Object.keys(b.query).length - Object.keys(a.query).length;",
  "  });",
  "  const choice = matching[0] || choices[0];",
  "  if (!choice) return;",
  "  host.innerHTML = choice.html;",
  "  if (choice.title) document.title = choice.title;",
  "  if (choice.lang) document.documentElement.lang = choice.lang;",
  '  const description = document.querySelector(\'meta[name="description"]\');',
  '  if (description) description.setAttribute("content", choice.description || "");',
  "  // Scripts inserted by innerHTML are inert. Recreate only executable authored",
  "  // scripts in DOM order; keep application/json page data as non-executable.",
  "  // Match HTML script MIME essences exactly: MIME parameters create inert data blocks.",
  "  function scriptType(script) {",
  '    const language = script.getAttribute("language") || "";',
  '    return (script.hasAttribute("type") ? script.getAttribute("type") || "text/javascript" : language ? "text/" + language : "text/javascript").toLowerCase();',
  "  }",
  "  function executable(script) {",
  "    const type = scriptType(script);",
  '    const classic = script.hasAttribute("type") ? type.replace(/^[\\t\\n\\f\\r ]+|[\\t\\n\\f\\r ]+$/g, "") : type;',
  '    return type === "module" || type === "importmap" ||',
  '      /^(?:application\\/(?:x-)?(?:javascript|ecmascript)|text\\/(?:(?:x-)?(?:javascript|ecmascript)|javascript1\\.[0-5]|jscript|livescript))$/.test(classic);',
  "  }",
  "  function appendRuntime(src) {",
  "    return new Promise(function (done) {",
  '      const script = document.createElement("script");',
  "      script.src = src;",
  "      script.onload = script.onerror = done;",
  "      document.body.appendChild(script);",
  "    });",
  "  }",
  "  async function start() {",
  '    for (const old of Array.from(host.querySelectorAll("script"))) {',
  "      if (!executable(old)) continue;",
  "      const type = scriptType(old);",
  "      // Modern browsers ignore classic nomodule scripts without a load event.",
  '      if (type !== "module" && type !== "importmap" && old.noModule) continue;',
  '      const script = document.createElement("script");',
  "      for (const attribute of Array.from(old.attributes)) {",
  "        script.setAttribute(attribute.name, attribute.value);",
  "      }",
  "      script.text = old.textContent;",
  '      const loaded = (old.hasAttribute("src") || type === "module") && type !== "importmap"',
  "        ? new Promise(function (done) { script.onload = script.onerror = done; }) : null;",
  "      old.replaceWith(script);",
  "      if (loaded) await loaded;",
  "    }",
  "    // The data loader must create __pageDataReady before scripts.js reads it.",
  "    for (const src of runtimeSources) await appendRuntime(src);",
  "  }",
  '  void start().catch(function (error) { console.error("Query variant bootstrap failed", error); });',
  "})();",
  "",
].join("\n");
