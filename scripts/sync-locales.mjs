/**
 * ビルドのときに言語を見つける。lib/locales/<BCP-47>.ts を追加して、npm run
 * dev/build/typecheck/test を実行すると、軽量な言語の一覧と、遅延 import の対応表が
 * 作り直される。登録の一覧を手で保守する必要は無い。
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const localeDirectory = join(root, "lib", "locales");
const GENERATED = new Set(["index.ts", "languages.generated.ts", "loaders.generated.ts"]);

export function generateLocaleSources(fileNames) {
  const languages = [];
  const seen = new Set();
  for (const name of [...fileNames].sort()) {
    if (!name.endsWith(".ts") || GENERATED.has(name)) continue;
    const raw = name.slice(0, -3);
    if (!/^[a-z]{2,3}(?:-[a-z0-9]{2,8})*$/i.test(raw)) {
      throw new Error("Invalid locale filename (expected a BCP 47 tag): " + name);
    }
    const canonical = Intl.getCanonicalLocales(raw)[0];
    const code = canonical.toLowerCase();
    if (code === "en") {
      throw new Error("en is the English source language; do not add en.ts");
    }
    if (seen.has(code)) throw new Error("Duplicate locale code: " + code);
    seen.add(code);
    const native = new Intl.DisplayNames([canonical], { type: "language" }).of(canonical) ?? canonical;
    const label = native.slice(0, 1).toLocaleUpperCase(canonical) + native.slice(1);
    languages.push({ code, filename: raw, label });
  }
  if (!seen.has("ja")) throw new Error("lib/locales/ja.ts is required");

  // 既存の言語の選択肢の順序と表示名を保つ。
  const other = languages.filter((item) => item.code !== "ja").sort((a, b) => a.code.localeCompare(b.code));
  const list = [
    { code: "ja", label: "日本語" },
    { code: "en", label: "English" },
    ...other.map(({ code, label }) => ({ code, label })),
  ];
  const header = "// Generated by scripts/sync-locales.mjs. Do not edit manually.\n";
  const languagesSource = header +
    "export const REGISTERED_LANGUAGES = {\n" +
    list.map(({ code, label }) =>
      "  " + JSON.stringify(code) + ": { label: " + JSON.stringify(label) + " },\n").join("") +
    "} as const;\n";
  const loadersSource = header +
    'import type { Dict } from "../i18n";\n' +
    'import type { Lang } from "../lang";\n\n' +
    "export const LOCALES: Partial<Record<Lang, () => Promise<Dict>>> = {\n" +
    languages.map(({ code, filename }) =>
      "  " + JSON.stringify(code) + ': () => import(' + JSON.stringify("./" + filename) + ').then((m) => m.default),\n').join("") +
    "};\n";
  return { languagesSource, loadersSource };
}

export function syncLocales() {
  const output = generateLocaleSources(readdirSync(localeDirectory));
  for (const [name, content] of [
    ["languages.generated.ts", output.languagesSource],
    ["loaders.generated.ts", output.loadersSource],
  ]) {
    const file = join(localeDirectory, name);
    if (!existsSync(file) || readFileSync(file, "utf8") !== content) {
      writeFileSync(file, content);
      console.log("Updated lib/locales/" + name);
    }
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  syncLocales();
}
